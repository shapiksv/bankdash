import { useState, type FormEvent } from 'react'
import { ACCOUNT_TYPES, type AccountType, type Card } from '../api/cards'
import { FormAlert, PrimaryButton, SelectField, TextField } from '../components/form'
import { pinError } from './pinRules'
import { useAddCard } from './queries'
import { CancelButton, Modal } from './Modal'

const ACCOUNT_LABELS: Record<AccountType, string> = { CHECKING: 'Checking', SAVINGS: 'Savings' }

interface AddCardDialogProps {
  onAdded: (card: Card) => void
  onCancel: () => void
}

/**
 * A new debit card on the user's Checking or Savings account. The number, holder name and expiry are generated by
 * account-service, so only the account and a PIN are asked for; the card is active right away.
 */
export function AddCardDialog({ onAdded, onCancel }: AddCardDialogProps) {
  const add = useAddCard()
  const [accountType, setAccountType] = useState<AccountType>('CHECKING')
  const [pin, setPin] = useState('')
  const [error, setError] = useState<string>()

  function onSubmit(event: FormEvent) {
    event.preventDefault()
    const weak = pinError(pin)
    setError(weak)
    if (weak) return
    add.mutate({ accountType, pin }, { onSuccess: onAdded })
  }

  return (
    <Modal title="Add card" onClose={onCancel}>
      <form noValidate onSubmit={onSubmit} className="flex flex-col gap-4">
        {add.isError && <FormAlert>{add.error.message}</FormAlert>}
        <SelectField
          label="Account"
          value={accountType}
          onChange={(event) => setAccountType(event.target.value as AccountType)}
          options={ACCOUNT_TYPES.map((type) => ({ value: type, label: ACCOUNT_LABELS[type] }))}
        />
        <TextField
          label="PIN"
          type="password"
          inputMode="numeric"
          autoComplete="off"
          maxLength={4}
          value={pin}
          onChange={(event) => {
            setPin(event.target.value)
            setError(undefined)
            add.reset()
          }}
          error={error}
          hint="4 digits, not easy to guess"
        />
        <div className="flex justify-end gap-3">
          <CancelButton onClick={onCancel} disabled={add.isPending} />
          <PrimaryButton type="submit" disabled={add.isPending}>
            {add.isPending ? 'Adding…' : 'Add card'}
          </PrimaryButton>
        </div>
      </form>
    </Modal>
  )
}
